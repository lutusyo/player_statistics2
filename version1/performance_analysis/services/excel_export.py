
from io import BytesIO

from django.http import HttpResponse
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter


HEADER_FILL = PatternFill("solid", fgColor="17365D")
SUBHEADER_FILL = PatternFill("solid", fgColor="D9EAF7")
WHITE_FONT = Font(color="FFFFFF", bold=True)
TITLE_FONT = Font(size=16, bold=True, color="17365D")
BOLD_FONT = Font(bold=True)
THIN_BORDER = Border(
    bottom=Side(style="thin", color="D9E1F2")
)


def style_sheet(ws):
    ws.freeze_panes = "A2"
    ws.sheet_view.showGridLines = False

    for cell in ws[1]:
        cell.fill = HEADER_FILL
        cell.font = WHITE_FONT
        cell.alignment = Alignment(
            horizontal="center",
            vertical="center",
            wrap_text=True,
        )

    ws.row_dimensions[1].height = 30

    for row in ws.iter_rows(min_row=2):
        for cell in row:
            cell.border = THIN_BORDER
            cell.alignment = Alignment(vertical="center")

    for column_cells in ws.columns:
        column_letter = get_column_letter(column_cells[0].column)
        max_length = max(
            (len(str(cell.value or "")) for cell in column_cells),
            default=0,
        )
        ws.column_dimensions[column_letter].width = min(
            max(max_length + 3, 14), 35
        )

    if ws.max_row > 1:
        ws.auto_filter.ref = ws.dimensions


def add_table_sheet(wb, title, headers, rows):
    ws = wb.create_sheet(title)
    ws.append(headers)

    for row in rows:
        ws.append(row)

    style_sheet(ws)
    return ws


def export_analysis_excel(run):
    report = run.results_snapshot or {}

    wb = Workbook()
    summary = wb.active
    summary.title = "Summary"
    summary.sheet_view.showGridLines = False

    analysis = report.get("analysis", {})
    periods = report.get("periods", [])
    teams = report.get("teams", [])
    results = report.get("results", [])
    comparisons = report.get("comparisons", [])
    insights = report.get("insights", [])
    player_analysis = report.get("player_analysis", [])

    # SUMMARY
    summary.merge_cells("A1:B1")
    summary["A1"] = "FOOTBALL PERFORMANCE ANALYSIS"
    summary["A1"].font = TITLE_FONT
    summary["A1"].alignment = Alignment(vertical="center")
    summary.row_dimensions[1].height = 32

    summary_data = [
        ("Analysis", analysis.get("name", run.analysis.name)),
        ("Analysis Type", analysis.get("analysis_type", "")),
        (
            "Generated",
            run.generated_at.strftime("%d %B %Y, %H:%M")
            if run.generated_at else "",
        ),
        ("Generated By", str(run.generated_by) if run.generated_by else ""),
        ("Number of Teams", len(teams)),
        ("Number of Periods", len(periods)),
    ]

    for label, value in summary_data:
        summary.append([label, value])

    for row in range(2, summary.max_row + 1):
        summary.cell(row, 1).font = BOLD_FONT
        summary.cell(row, 1).fill = SUBHEADER_FILL

    summary.column_dimensions["A"].width = 24
    summary.column_dimensions["B"].width = 40

    # TEAM PERFORMANCE
    performance_headers = [
        "Period", "Start Date", "End Date", "Age Group", "Team",
        "Played", "Won", "Drawn", "Lost", "Goals For", "Goals Against",
        "Goal Difference", "Points", "Win %", "Players Used",
        "Appearances", "Starting Appearances", "Substitute Appearances",
        "Unused Substitutes", "Total Player Minutes",
        "Average Minutes per Appearance", "Shots", "Shots on Target",
        "Shooting Accuracy %", "Passes Attempted", "Passes Completed",
        "Passing Accuracy %",
    ]

    performance_rows = []

    for item in results:
        performance_rows.append([
            item.get("period_name"),
            item.get("start_date"),
            item.get("end_date"),
            item.get("age_group"),
            item.get("team_name"),
            item.get("played", 0),
            item.get("won", 0),
            item.get("drawn", 0),
            item.get("lost", 0),
            item.get("goals_for", 0),
            item.get("goals_against", 0),
            item.get("goal_difference", 0),
            item.get("points", 0),
            item.get("win_percentage", 0),
            item.get("players_used", 0),
            item.get("player_appearances", 0),
            item.get("starting_appearances", 0),
            item.get("substitute_appearances", 0),
            item.get("unused_substitutes", 0),
            item.get("total_player_minutes", 0),
            item.get("average_minutes_per_appearance", 0),
            item.get("shots", 0),
            item.get("shots_on_target", 0),
            item.get("shooting_accuracy", 0),
            item.get("passes_attempted", 0),
            item.get("passes_completed", 0),
            item.get("pass_accuracy", 0),
        ])

    add_table_sheet(
        wb, "Team Performance", performance_headers, performance_rows
    )

    # PERIOD COMPARISONS
    comparison_headers = [
        "Team", "Period", "Previous Period", "Metric",
        "Current Value", "Previous Value", "Change",
    ]

    comparison_rows = []

    for item in comparisons:
        current = item.get("current") or {}
        previous = item.get("previous") or {}
        changes = item.get("changes") or {}

        for metric, change in changes.items():
            comparison_rows.append([
                item.get("team_name"),
                item.get("period_name"),
                item.get("previous_period_name") or "No previous period",
                metric.replace("_", " ").title(),
                current.get(metric, ""),
                previous.get(metric, "") if previous else "",
                change if change is not None else "",
            ])

    add_table_sheet(
        wb, "Period Comparisons", comparison_headers, comparison_rows
    )

    # PERFORMANCE INSIGHTS
    insight_headers = [
        "Period", "Team", "Category", "Metric", "Status", "Observation"
    ]
    insight_rows = []

    for item in insights:
        for insight in item.get("insights", []):
            insight_rows.append([
                item.get("period_name"),
                item.get("team_name"),
                insight.get("category"),
                insight.get("metric"),
                insight.get("status"),
                insight.get("message"),
            ])

    add_table_sheet(
        wb, "Performance Insights", insight_headers, insight_rows
    )

    # PLAYER MINUTES
    player_headers = [
        "Period", "Age Group", "Team", "Player",
        "Appearances", "Total Minutes",
    ]
    player_rows = []

    for item in results:
        for player in item.get("player_details", []):
            player_rows.append([
                item.get("period_name"),
                item.get("age_group"),
                item.get("team_name"),
                player.get("player_name"),
                player.get("appearances", 0),
                player.get("minutes", 0),
            ])

    add_table_sheet(
        wb, "Player Minutes", player_headers, player_rows
    )

    # PLAYER PERFORMANCE
    player_performance_headers = [
        "Period", "Team", "Player",
        "Appearances", "Starts", "Substitute Appearances",
        "Total Minutes", "Average Minutes",
        "Goals", "Assists", "Pre-assists",
        "Goal Contributions", "Shots", "Shots on Target",
        "Goals per Appearance",
    ]

    player_performance_rows = []

    for period in player_analysis:
        for team in period.get("teams", []):
            for player in team.get("players", []):
                player_performance_rows.append([
                    period.get("period_name"),
                    team.get("team_name"),
                    player.get("player_name"),
                    player.get("appearances", 0),
                    player.get("starts", 0),
                    player.get("substitute_appearances", 0),
                    player.get("minutes", 0),
                    player.get("average_minutes_per_appearance", 0),
                    player.get("goals", 0),
                    player.get("assists", 0),
                    player.get("pre_assists", 0),
                    player.get("goal_contributions", 0),
                    player.get("shots", 0),
                    player.get("shots_on_target", 0),
                    player.get("goals_per_appearance", 0),
                ])

    add_table_sheet(
        wb,
        "Player Performance",
        player_performance_headers,
        player_performance_rows,
    )

    # PAGE SETUP
    for ws in wb.worksheets:
        if ws.title != "Summary":
            ws.sheet_properties.pageSetUpPr.fitToPage = True
            ws.page_setup.fitToWidth = 1
            ws.page_setup.fitToHeight = 0
            ws.page_setup.orientation = "landscape"

    output = BytesIO()
    wb.save(output)
    output.seek(0)

    filename = f"performance_analysis_{run.id}.xlsx"

    response = HttpResponse(
        output.getvalue(),
        content_type=(
            "application/vnd.openxmlformats-officedocument."
            "spreadsheetml.sheet"
        ),
    )
    response["Content-Disposition"] = (
        f'attachment; filename="{filename}"'
    )

    return response
